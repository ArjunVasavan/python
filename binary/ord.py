'''ord is used to convert character to is ASCII integer values'''

ord('a')   # 97
ord('b')   # 98
ord('A')   # 65
ord('z')   # 122

print(ord('0'))
print(ord('A'))
print(ord('a'))

'''When you want to use c logic of indexing on here use'''

print(ord('a') - ord('a'))  # result will be zero 
print(ord('A') - ord('A'))  # result will be zero 
print(ord('0') - ord('0'))  # result will be zero 
